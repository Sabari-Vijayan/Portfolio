import fs from 'fs';
import path from 'path';

const GITHUB_USERNAME = 'Sabari-Vijayan';
const OUTPUT_FILE = path.join(process.cwd(), 'src/data/projects.ts');

async function sync() {
  console.log(`Fetching repositories for ${GITHUB_USERNAME}...`);
  
  try {
    const response = await fetch(`https://api.github.com/users/${GITHUB_USERNAME}/repos?sort=updated&per_page=100`);
    if (!response.ok) throw new Error(`GitHub API error: ${response.statusText}`);
    
    const repos = await response.json();
    
    // Filter out forks and keep only repos with descriptions (or whatever filter you like)
    const featuredRepos = repos.filter(repo => !repo.fork && repo.description);

    let projectsMarkdown = `# SABARI VIJAYAN - AUTOMATED PROJECT INDEX\n\n`;
    let repoMapping = {};
    let projectList = [];

    featuredRepos.forEach((repo, index) => {
      projectsMarkdown += `## ${repo.name}\n`;
      projectsMarkdown += `- Description: ${repo.description}\n`;
      projectsMarkdown += `- Primary Language: ${repo.language || 'Mixed'}\n`;
      projectsMarkdown += `- Stars: ${repo.stargazers_count} | Forks: ${repo.forks_count}\n`;
      projectsMarkdown += `- URL: ${repo.html_url}\n`;
      if (repo.homepage) projectsMarkdown += `- Live Site: ${repo.homepage}\n`;
      projectsMarkdown += `\n`;

      repoMapping[repo.name.toLowerCase()] = repo.full_name;
      
      projectList.push({
        id: index + 1,
        title: repo.name,
        category: 'PROJECT',
        description: repo.description,
        link: repo.html_url,
        date: new Date(repo.updated_at).getFullYear().toString()
      });
    });

    const fileContent = `
// THIS FILE IS AUTOMATICALLY GENERATED BY .github/workflows/update-projects.yml
// DO NOT EDIT MANUALLY.

export const repoMapping: Record<string, string> = ${JSON.stringify(repoMapping, null, 2)};

export const projectList = ${JSON.stringify(projectList, null, 2)};

export const projectsData = \`
${projectsMarkdown}
Users can browse all projects on the [Portfolio Hub](/portfolio).
\`;
`;

    fs.writeFileSync(OUTPUT_FILE, fileContent.trim());
    console.log(`Successfully updated ${OUTPUT_FILE} with ${featuredRepos.length} projects.`);
  } catch (error) {
    console.error('Sync failed:', error);
    process.exit(1);
  }
}

sync();
